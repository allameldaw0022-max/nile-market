/**
 * ★ فكّ ترميز معاملات المسار في مساحة المتجر.
 *
 * السبب — سلوك مثبَت في Next.js 16 (16.3.3): بعد إعادة الكتابة من
 * الـproxy (`/products/%D8%B1...` ⟶ `/sites/<host>/products/%D8%B1...`)
 * تصل القيمة إلى **مكوّن الصفحة** مرمَّزة كما هي، بينما تصل إلى
 * `generateMetadata` مفكوكة. فكل مسار عربي كان يقارن
 * `slug = '%D8%B1%D9%88%D9%84-...'` بقيمة عربية في القاعدة ⇒ لا
 * تطابق ⇒ `notFound()` ⇒ 404 لكل منتج وكل تصنيف عنوانه بالعربية.
 *
 * ولا يمكن إصلاحه في الـproxy: `URL.pathname` يعيد ترميز أي حرف
 * غير ASCII عند الإسناد (WHATWG)، فمهما سلّمناه نصًا مفكوكًا عاد
 * مرمَّزًا. الإصلاح هنا — عند الاستهلاك — هو الموضع الوحيد الممكن.
 *
 * الفكّ آمن ومرّة واحدة:
 *  · لا `%` في القيمة ⇒ تُعاد كما هي (حالة القيمة المفكوكة مسبقًا،
 *    كما في `generateMetadata`، وحالة كل المسارات الإنجليزية).
 *  · ترميز تالف (`%ZZ`) ⇒ تُعاد كما هي، ولا يُرمى استثناء يُسقط
 *    الصفحة بـ500 بدل 404.
 *  · `%2F` ⇒ لا يُفكّ: شرطة مائلة داخل مقطع تغيّر بنية المسار،
 *    وهذا مدخل تجاوزٍ لا نفتحه.
 *
 * و`app.slugify` تحصر الـslug في `[a-z0-9؀-ۿ-]`، فلا يحمل slug
 * حقيقي علامة `%` ⇒ لا خطر فكّ مزدوج.
 */
export function decodeSlugParam(value: string): string {
  if (!value.includes('%')) return value;
  try {
    const decoded = decodeURIComponent(value);
    return decoded.includes('/') ? value : decoded;
  } catch {
    return value;
  }
}
