/**
 * نص البحث: تنظيف وتحديد طول في مكان واحد.
 *
 * ★ لماذا ملف مستقل: بناء `or(...)` في PostgREST يتم بلصق نص المستخدم
 * داخل صيغة `name.ilike."%…%"`. حروف الصيغة — `"` و`,` و`(` و`)` —
 * تكسر التعبير وتسمح بإضافة شروط لم يقصدها الكود. RLS تبقى الحاجز
 * الأخير، لكن التعبير المكسور يقرأ أعمدة وصفوفًا خارج نيّة الصفحة.
 *
 * كان التنظيف منسوخًا حرفيًا في خمسة ملفات — وقد انحرفت النسخ فعلًا:
 * أربع صفحات تحدّ الطول (٦٠ أو ٨٠ حرفًا) وصفحة منتجات لوحة التاجر لا
 * تحدّه أصلًا، فيمرّ نص بطول غير محدود إلى `ilike` بعلامات `%`. لذلك
 * صار الحدّ والتنظيف عملية واحدة لا يمكن استدعاء نصفها.
 */

/** أقصى طول لنص بحث. أطول من ذلك لا يضيف دقّة، ويُثقل `ilike`. */
export const SEARCH_TERM_MAX = 80;

/**
 * يقرأ نص البحث من `searchParams` ويعيده نظيفًا محدود الطول.
 * يعيد `''` لأي مدخل ليس نصًا أو لا يبقى منه شيء بعد التنظيف.
 */
export function searchTerm(raw: unknown, max: number = SEARCH_TERM_MAX): string {
  if (typeof raw !== 'string') return '';
  return raw
    .trim()
    .slice(0, max)
    .replace(/["'(),*\\]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * يبني تعبير `or` للبحث في أعمدة نصّية.
 * يعيد `null` إذا لم يبقَ نص بحث — فيتخطّى المنادي الفلترة كلها.
 */
export function ilikeAny(term: string, columns: readonly string[]): string | null {
  if (!term) return null;
  return columns.map((c) => `${c}.ilike."%${term}%"`).join(',');
}
