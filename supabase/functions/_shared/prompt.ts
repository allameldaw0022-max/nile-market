const FENCE_OPEN = '===== نصّ التذكرة (بيانات) =====';
const FENCE_CLOSE = '===== نهاية نصّ التذكرة =====';

/**
 * ★★ تنقية الفاصل: نصٌّ يحوي سطرًا مثل الفاصل يستطيع أن «يُغلق»
 *    البيانات ثم يكتب تعليماتٍ تبدو من النظام. فكل سطرٍ يشبه الفاصل
 *    يُكسر بمسافة — يبقى مقروءًا ولا يبقى فاصلًا.
 */
const defuse = (text: string) => text
  .split('\n')
  .map((line) => (/^\s*={3,}/.test(line) ? line.replace(/=/g, '= ') : line))
  .join('\n');

/** أقصى ما يُقتطع من نصّ المحادثة — حماية من تذكرةٍ ضخمة. */
export const MAX_CONVERSATION_CHARS = 6000;
/** أقصى ما يُقتطع من مقاطع المعرفة. */
export const MAX_CONTEXT_CHARS = 9000;

const clip = (text: string, max: number) =>
  text.length <= max ? text : `${text.slice(0, max)}\n…[اقتُطع]`;

export function buildUserPrompt(
  ticket: TicketFacts,
  conversation: { authorKind: string; body: string }[],
  hits: KbHit[],
): string {
  const context = hits
    .map((hit, index) =>
      `--- مقطع ${index + 1} · ${hit.section} · تشابه ${hit.similarity.toFixed(3)} ---\n${hit.content}`)
    .join('\n\n');

  const thread = conversation
    .map((message) => `[${message.authorKind === 'requester' ? 'التاجر' : message.authorKind}] ${message.body}`)
    .join('\n\n');

  return [
    `تذكرة ${ticket.ticketNumber} · تصنيف التاجر: ${ticket.category} · أولوية: ${ticket.priority}`,
    `الموضوع: ${ticket.subject}`,
    '',
    'مقاطع المعرفة:',
    clip(context, MAX_CONTEXT_CHARS) || '(لا مقاطع)',
    '',
    FENCE_OPEN,
    clip(defuse(thread), MAX_CONVERSATION_CHARS),
    FENCE_CLOSE,
  ].join('\n');
}
