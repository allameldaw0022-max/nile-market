-- 0054 إصلاح هويّة المُحدَّد في حدّ إنشاء الطلبات
--
-- كشفه اختبار الضغط، لا التدقيق النظري: الحدّ الذي أضافته 0052
-- **لا يعمل إطلاقًا** على المسار الذي كُتب من أجله.
-- =====================================================================

-- ★ الخطأ: 0052 حلّت هويّة المُحدَّد هكذا
--     coalesce(customer_id, guest_token, contact_phone)
--   على افتراض أنّ `guest_token` هو توكن جلسة الزائر — وهو ليس كذلك.
--   في `create_order` (0039 سطر 78) يُولَّد التوكن لحظة الطلب:
--       v_guest text := app.random_token(16);
--   أي أنّه سرّ **خاصّ بالطلب** يُعاد للزائر ليتابع طلبه، وليس
--   مميِّزًا لصاحبه. فكل طلب يحمل توكنًا جديدًا ⇒ دلو جديد
--   ⇒ العدّاد يبقى ١ أبدًا ⇒ لا حدّ.
--
-- ★ القياس لا الاستنتاج: ١٢ طلبًا متتاليًا من نفس الهاتف على نفس
--   المتجر (بمفاتيح idempotency مختلفة) نجحت كلّها، وقاعدة الاختبار
--   انتهت إلى ١٦٠١٠ دلوًا كلّ واحد بعدّاد = ١. والحدّ ٥ لكل ٦٠٠ ثانية.
--
-- ★ ومن يتأثّر؟ الزائر بلا حساب تحديدًا — أي المهاجم الذي كُتب
--   الحدّ لأجله؛ فالعميل المسجَّل كان محدودًا فعلًا لأنّ
--   `customer_id` يسبق التوكن في السلسلة.
--
-- ★ الإصلاح: يُسقَط `guest_token` من السلسلة. الهويّة الثابتة
--   المتاحة على صفّ الطلب لزائرٍ بلا حساب هي رقم الهاتف
--   (`contact_phone` — not null بحكم المخطّط)، ثمّ البريد.
--
-- ★ ما لا يعالجه هذا الإصلاح (ولا نُدّعي غيره): مهاجمٌ يدوّر أرقام
--   الهواتف يبقى قادرًا على الإغراق، لأنّ أيّ حدٍّ في القاعدة لا
--   يرى إلّا ما يُرسله العميل. الحدّ الذي يوقف ذلك هو حدّ على
--   مستوى الحافة (IP/WAF)، وهو خارج نطاق القاعدة.
create or replace function app.enforce_order_rate()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor text;
begin
  -- طلبات اللوحة من التاجر نفسه لا تُحدّ: هو صاحب المتجر لا زائر.
  if new.placed_via <> 'storefront' then
    return null;
  end if;

  -- هويّة ثابتة بين طلب وطلب: الحساب، وإلا الهاتف، وإلا البريد.
  -- ★ `guest_token` ليس هويّة: يُولَّد عشوائيًا لكل طلب (0039).
  -- ★ ولا مفتاح عامّ بلا مميِّز: دلوٌ واحد لكل زوّار المتجر يجعل
  --   الحدّ نفسه سلاح حرمان خدمة.
  v_actor := coalesce(new.customer_id::text,
                      nullif(new.contact_phone, ''),
                      nullif(new.contact_email, ''));
  if v_actor is null then
    return null;
  end if;

  if not public.check_rate_limit(
       'order:' || new.store_id::text || ':' || v_actor, 5, 600) then
    raise exception 'RATE_LIMITED: تجاوزت عدد الطلبات المسموح. حاول بعد قليل.'
      using errcode = 'P0001';
  end if;

  return null;
end;
$$;

-- الدلاء التي خلّفها السلوك المعطوب: صفٌّ لكل طلب، بعدّاد ١، لا
-- يُقرأ أبدًا. تُزال مرّة واحدة — بيانات عدّادات لا بيانات عمل.
-- ★ يُحصر الحذف بالدلاء اليتيمة (count = 1) حتى لا يُمسح عدّادٌ
--   حقيقي قائم لعميل مسجَّل داخل نافذته.
delete from public.rate_limit_counters
where bucket like 'order:%'
  and count = 1
  and window_start < now() - interval '600 seconds';
