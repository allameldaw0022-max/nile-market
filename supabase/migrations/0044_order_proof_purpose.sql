-- =====================================================================
-- 0044 غرض وسائط جديد: إيصال تحويل الطلب (إضافي · لا يمسّ ما سبق)
--
-- لماذا غرض مستقل عن `payment_proof`؟
--   * `payment_proof` = إيصال اشتراك المنصة: يرفعه **التاجر**،
--     ويراجعه **موظف سوق النيل**.
--   * `order_payment_proof` = إيصال تحويل طلب في متجر: يرفعه
--     **زبون المتجر**، ويراجعه **صاحب المتجر**.
-- مَن يرفع ومَن يراجع ومَن يقرأ مختلفون في الحالتين، وخلطهما في غرض
-- واحد يعني سياسة قراءة واحدة لملفّين لا يجوز أن يراهما نفس الشخص.
--
-- ★ `alter type … add value` وحده في هذه الترحيلة: القيمة الجديدة لا
-- تُستعمل في نفس المعاملة التي أضافتها، فتُفصل عمّا يستعملها (0045).
-- =====================================================================

do $$
begin
  if not exists (
    select 1 from pg_enum e
    join pg_type t on t.oid = e.enumtypid
    where t.typname = 'media_purpose' and e.enumlabel = 'order_payment_proof'
  ) then
    alter type public.media_purpose add value 'order_payment_proof';
  end if;
end $$;
