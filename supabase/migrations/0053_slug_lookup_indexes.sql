-- 0053 فهرسا البحث بالـslug (إضافيان · لا تغيير منطق)
--
-- ★ الاكتشاف: الفهارس الفريدة على `(store_id, lower(slug))` تحرس
-- التفرّد ولا تخدم القراءة. الواجهة تستعلم بـ`.eq('slug', slug)`
-- أي `slug = '...'` بلا `lower()`، ولا يستطيع المخطِّط استعمال فهرس
-- دالّي إلا إذا طابق التعبير حرفيًّا. فصفحة المنتج كانت تمسح صفوف
-- المتجر كلّها وتُرشّحها واحدًا واحدًا.
--
-- ★ قياس فعلي على متجر بـ١٠٥٠ منتجًا (سقف الباقة الاحترافية ١٠٠٠):
--
--     قبل: Bitmap Heap Scan · Rows Removed by Filter: 1049 · 223 buffer
--     بعد: Index Scan       · Rows Removed: 0              ·   5 buffer
--
-- أي أنّ كلفة فتح صفحة منتج كانت تنمو **طرديًّا** مع عدد منتجات
-- المتجر: التاجر الناجح يعاقَب على نجاحه، وصفحته تبطؤ كلّما أضاف
-- بضاعة. هذا هو الشكل الذي ينهار به النظام تحت الضغط — لا فجأةً
-- بل بالتدريج ومع أكثر المتاجر نشاطًا.
--
-- ★ ولا يُحذف الفهرس الفريد ولا يُعدَّل: هو يحرس التفرّد بلا حساسية
-- لحالة الأحرف، وهذه وظيفة أخرى. الفهرسان يتعايشان.
create index if not exists products_store_slug_idx
  on public.products (store_id, slug) where deleted_at is null;

-- ونفس النمط في التصنيفات (أقلّ أثرًا لقلّة الصفوف، ونفس العلّة)
create index if not exists categories_store_slug_idx
  on public.categories (store_id, slug) where deleted_at is null;
